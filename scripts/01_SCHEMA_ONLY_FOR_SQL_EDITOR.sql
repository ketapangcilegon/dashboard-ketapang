-- -------------------------------------------------------------------------------------
-- RPC Function: increment_visit_count(target_path TEXT)
-- -------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.increment_visit_count(target_path TEXT)
RETURNS BIGINT AS $$
DECLARE
  new_count BIGINT;
BEGIN
  UPDATE public.page_visits
  SET total_count = total_count + 1,
      last_visited_at = now()
  WHERE page_path = target_path
  RETURNING total_count INTO new_count;

  IF new_count IS NULL THEN
    INSERT INTO public.page_visits (page_path, total_count)
    VALUES (target_path, 1)
    RETURNING total_count INTO new_count;
  END IF;

  RETURN new_count;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- -------------------------------------------------------------------------------------
-- RPC Function: sync_all_sequences() — Syncs BIGINT identity sequences after bulk seed
-- -------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sync_all_sequences()
RETURNS TEXT AS $$
DECLARE
  rec RECORD;
  seq_name TEXT;
  max_id BIGINT;
BEGIN
  FOR rec IN
    SELECT table_name
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND column_name = 'id'
      AND data_type IN ('bigint', 'integer')
  LOOP
    seq_name := pg_get_serial_sequence(format('public.%I', rec.table_name), 'id');
    IF seq_name IS NOT NULL THEN
      EXECUTE format('SELECT COALESCE(MAX(id), 1) FROM public.%I', rec.table_name) INTO max_id;
      PERFORM setval(seq_name, GREATEST(max_id, 1), true);
    END IF;
  END LOOP;
  RETURN 'ALL_SEQUENCES_SYNCED';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

